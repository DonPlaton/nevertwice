"""Build the supersession dataset, deterministically, from a table anyone can audit.

The dataset this writes is committed and content-hashed, which is the whole reason it is
generated by a script instead of typed into a JSON file: the last external corpus this
project published numbers against was third-party, uncommitted and unhashed, and every one
of those numbers had to be withdrawn. A reader must be able to regenerate this byte for byte
and see where each case came from.

**What a case is.** Two sessions written weeks apart, the way a real project accumulates
facts: session one states something, session two states what replaced it, and a query asks
what is true *now*. Each session carries a couple of neighbouring sentences, because a memory
that only ever sees a bare assertion is not being tested on anything a user will do, and
because an extraction pipeline with a relevance gate - this one has one - correctly declines
to store a single context-free sentence.

**Four shapes**, because "superseded" is not one thing:

* `value_replaced` - a number or a name changes and the old one is simply wrong now.
* `approach_abandoned` - a whole approach is dropped for a different one.
* `retracted_no_replacement` - something is removed and nothing takes its place. The hardest
  shape: there is no new fact for retrieval to rank above the old one.
* `narrowed` - the fact still holds, in a smaller scope than before. The old statement is not
  false so much as over-general, which is the failure mode that reads as correct.

**And controls.** A third of the cases assert two facts that are simply *different* and both
still true. They exist because the cheapest way to score zero on staleness is to forget
things, and without a column that punishes it, "delete on any doubt" wins the benchmark while
losing the product.

**Phrasing is rotated on purpose.** Six frames per role, assigned round-robin, so a system
cannot pass by keying on one sentence pattern. The frames are visible below rather than
generated, so a reader can see exactly how narrow or wide the linguistic variation is - and
controls get their own frames, because the first draft handed them the *replacement* frames
and a control session opened with "and it did not survive". A system that read that sentence
correctly was then scored as over-retracting for obeying it.

    python research/gen_supersession_dataset.py
    python research/gen_supersession_dataset.py --check    # verify the committed file matches
"""
