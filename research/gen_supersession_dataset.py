# ── narrative frames ──────────────────────────────────────────────────────────────────────
#
# Six per role, rotated by index, so no arm can pass by matching one sentence pattern.

ASSERT_FRAMES = [
    "Spent the session on {domain}. Settled it: {fact}.",
    "Worked through {domain} today. The outcome: {fact}.",
    "Picked up the {domain} thread again. Confirmed that {fact}.",
    "Reviewed how {domain} is set up. As of today, {fact}.",
    "Cleared the open question on {domain}: {fact}.",
    "Wrote up the {domain} decision. {fact}, and the code now matches.",
]

REPLACE_FRAMES = [
    "Came back to {domain}. That earlier decision is off: {fact}.",
    "Reopened {domain} after the last review. The new position: {fact}.",
    "{domain} changed this week. {fact}.",
    "Had to revisit {domain}. What holds now is that {fact}.",
    "Reversed the earlier call on {domain}: {fact}.",
    "Follow-up on {domain}, and it did not survive. {fact}.",
]

ADD_FRAMES = [
    "Separate thread on {domain} the same week: {fact}.",
    "Also landed, unrelated to the above: {fact}.",
    "Second item on {domain} this sprint. {fact}.",
    "While that was in review, a different piece of {domain} got settled: {fact}.",
    "Unrelated to the earlier change, {fact}.",
    "One more {domain} item, independent of the first: {fact}.",
]

#: Neighbouring sentences. They are deliberately uninformative about the fact under test:
#: their job is to make a session look like a session, not to carry signal.
FILLER = [
    "Ran the full test suite afterwards and it stayed green.",
    "Left a note in the tracker so the next person does not redo this.",
    "The change touched three files and none of them were config.",
    "Pairing session, roughly ninety minutes, no interruptions.",
    "Rolled it out behind the usual staged release.",
    "Checked the dashboards for an hour after and nothing moved.",
    "The reviewer asked for one rename and otherwise approved it.",
    "Documented it in the README section that was already stale.",
]


def _cap(fact: str) -> str:
    """A fact opening a sentence is capitalised; one continuing a clause is not."""
    return fact[:1].upper() + fact[1:] if fact else fact


def _frame(frames: list[str], i: int, domain: str, fact: str) -> str:
    tpl = frames[i % len(frames)]
    at = tpl.find("{fact}")
    starts_sentence = at > 0 and tpl[:at].rstrip().endswith((".", "!", "?"))
    return tpl.format(domain=domain, fact=_cap(fact) if starts_sentence else fact)


def _sessions(i: int, domain: str, first: str, second: str,
              frames: list[str]) -> list[list[str]]:
    """Two sessions: the first asserts, the second either replaces or simply adds."""
    return [[_frame(ASSERT_FRAMES, i, domain, first), FILLER[i % len(FILLER)]],
            [_frame(frames, i, domain, second), FILLER[(i + 3) % len(FILLER)]]]


#: The implicit variant (ledger H7 / I5, 2026-09-06). The replacement arrives with no
#: retraction cue at all - framed exactly like a first assertion, rotated so the two sessions
#: never share a frame - which is how a real transcript usually delivers it: nobody writes
#: "that earlier decision is off", they just state the new value. Same facts, same markers,
#: same query; only the second session's frame differs.
VARIANTS = {"explicit": REPLACE_FRAMES, "implicit": ASSERT_FRAMES}


def build(variant: str = "explicit") -> dict:
    cases = []
    groups = [("value_replaced", VALUE_REPLACED), ("approach_abandoned", APPROACH_ABANDONED),
              ("retracted_no_replacement", RETRACTED), ("narrowed", NARROWED)]
    replace_frames = VARIANTS[variant]
    offset = 2 if variant == "implicit" else 0        # never the first session's own frame
    i = 0
    for shape, table in groups:
        for cid, domain, old, new, query, current, superseded in table:
            sessions = _sessions(i, domain, old, new, replace_frames)
            if offset:
                sessions[1][0] = _frame(replace_frames, i + offset, domain, new)
            cases.append({
                "id": f"{shape[:3]}-{cid}", "shape": shape, "domain": domain,
                "sessions": sessions,
                "query": query, "current": current, "superseded": superseded,
            })
            i += 1
    for cid, domain, fact_a, fact_b, query, current in CONTROLS:
        cases.append({
            "id": cid, "shape": "control", "domain": domain,
            "sessions": _sessions(i, domain, fact_a, fact_b, ADD_FRAMES),
            "query": query, "current": current, "superseded": [],
        })
        i += 1
    # The explicit variant is the committed, content-hashed v1: its bytes must not move, so
    # only the other variants carry the extra keys.
    extra = {} if variant == "explicit" else {"variant": variant}
    return {
        "name": "supersession_v1" if variant == "explicit" else f"supersession_v1_{variant}",
        **extra,
        "generated_by": "research/gen_supersession_dataset.py"
                        + ("" if variant == "explicit" else f" --variant {variant}"),
        "license": "same as this repository - the cases are written here, not scraped",
        "shapes": {s: sum(1 for c in cases if c["shape"] == s)
                   for s in sorted({c["shape"] for c in cases})},
        "n": len(cases),
        "cases": cases,
    }


def validate(data: dict) -> list[str]:
    """Refuse to write a case no arm could ever score.

    Three ways a marker can be wrong, each of which silently shifts a rate:

    * a **current** marker that appears nowhere in the session asserting it - no system can
      return it, so every arm loses the case and the benchmark measures nothing;
    * a **superseded** marker missing from the session that asserts the old fact - the same
      failure, in the direction that flatters every arm;
    * a superseded marker that appears in the *replacement* text while no current marker
      does. That is the one that matters: the two-sided rule would then read a correct answer
      as a stale assertion, and the arm is punished for being right.
    """
    problems = []
    for c in data["cases"]:
        s1 = " ".join(c["sessions"][0]).lower()
        s2 = " ".join(c["sessions"][1]).lower()
        asserts_current = s1 if c["shape"] == "control" else s2
        if not any(m.lower() in asserts_current for m in c["current"]):
            problems.append(f"{c['id']}: current marker {c['current']} is not in its own session")
        if c["superseded"]:
            if not any(m.lower() in s1 for m in c["superseded"]):
                problems.append(f"{c['id']}: superseded marker {c['superseded']} is not in session 1")
            leaks = any(m.lower() in s2 for m in c["superseded"])
            covered = any(m.lower() in s2 for m in c["current"])
            if leaks and not covered:
                problems.append(f"{c['id']}: the replacement names the old fact and nothing "
                                f"marks it current, so a correct answer scores as stale")
    return problems


def serialise(data: dict) -> bytes:
    return (json.dumps(data, indent=1, ensure_ascii=False, sort_keys=False) + "\n").encode("utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed file differs from what this script builds")
    ap.add_argument("--variant", default="explicit", choices=sorted(VARIANTS),
                    help="explicit: the replacement carries a retraction frame (the committed "
                         "v1); implicit: it arrives framed like any first assertion")
    args = ap.parse_args()

    out = OUT if args.variant == "explicit" else OUT.with_name(f"supersession_v1_{args.variant}.json")
    data = build(args.variant)
    problems = validate(data)
    if problems:
        print("dataset is not writable - fix the table:")
        for line in problems:
            print("  ", line)
        return 1
    blob = serialise(data)
    digest = hashlib.sha256(blob).hexdigest()

    if args.check:
        if not out.exists():
            print(f"missing: {out}")
            return 1
        have = hashlib.sha256(out.read_bytes()).hexdigest()
        ok = have == digest
        print(f"{'ok' if ok else 'DRIFT'}  committed {have[:16]}  rebuilt {digest[:16]}")
        return 0 if ok else 1

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(blob)
    print(f"wrote {out.relative_to(HERE.parent)}  n={data['n']}  sha256={digest}")
    for shape, n in data["shapes"].items():
        print(f"  {shape:26s} {n}")
    return 0


