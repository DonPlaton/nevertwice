#!/usr/bin/env python3
"""The evidence contract: no public number without traceable evidence.

`research/evidence_manifest.json` is the register. This suite enforces three things:

1. **Schema** - every claim carries the fields that make it checkable, and every
   dataset/environment reference resolves.
2. **Agreement with the raw results** - a claim that points into a committed result
   file must equal what that file actually says. Transcription drift dies here.
3. **Coverage** - every number printed in the documents the manifest claims to cover
   resolves to a claim, a quoted third-party citation, a declared non-metric, or a
   recorded drift entry. An unaccounted number is a claim with no evidence.
4. **Governance** - every tracked `.md` is registered as governed, exempt with a
   reason, or backlog with a budget that may only be lowered. A new document cannot
   quietly start publishing unevidenced numbers, and the unregistered surface can
   only shrink. Numbers inside a generated region do not count against a budget:
   they come from committed data through a tool whose own check runs in CI.

The tables inside the governed documents are generated by `tools/render_claims.py`,
and this suite runs it in check mode - so a hand-edited table fails here.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))

import _env_guard  # noqa: F401, E402 - must run before any project import
import _docs_scope  # noqa: E402 - one definition of "document"

MANIFEST_PATH = ROOT / "research" / "evidence_manifest.json"

PASSED = 0
FAILED = 0


def check(name: str, condition: bool, detail: str = "") -> None:
    global PASSED, FAILED
    suffix = f"  [{detail}]" if detail and not condition else ""
    print(("  ok   " if condition else "  FAIL ") + name + suffix)
    PASSED += int(condition)
    FAILED += int(not condition)


MANIFEST = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))

REQUIRED = ("id", "statement", "value", "printed", "unit", "dataset", "environment",
            "n", "command", "raw", "pointer", "commit", "ci", "cited_in")

# Fenced blocks are shell commands and illustrative terminal output, not measurements.
FENCE = re.compile(r"^```.*?^```", re.S | re.M)
NUMBER = re.compile(r"\d+(?:,\d{3})*(?:\.\d+)?")
# IDs are not measurements. This project numbers its own findings/decisions/campaigns/tracks
# (WEAKNESSES.md's W<N>, PLAN's R<N> risks, decision D<N>s, campaigns K<N>/A<N>/B<N>/C<N>[a-z]/
# Q<N>/M<N>/F<N>/N<N>/H<N>/P<N>, and G5.1-style gate numbers with an optional dotted sub-index)
# - a register tag, never a count or a percentage. The coordinator's finding (C7, 2026-09-23):
# disguising an ID as a spelled-out word ("W17" -> "W-Seventeen") to dodge the numeric-token
# count breaks every existing cross-reference to that ID (grep W17 no longer finds the entry)
# without removing anything real - the fix belongs in the COUNTER, recognizing the ID shape and
# excluding THAT SPECIFIC OCCURRENCE, not in the document. A bare digit elsewhere (a real
# measurement that happens to share the same value, e.g. "17%") is UNAFFECTED - this strips only
# the ID-shaped SPAN (letter + digits, whole token) before the plain NUMBER scan ever sees it,
# it does not exempt a value context-free. Anchored at both ends (`\b`) so it never matches
# inside a longer identifier (`raw17` is not `W17`); no decimal part except G's own dotted gate
# form (`G5.1`).
ID_TOKEN = re.compile(
    r"\b(?:W|R|D|K|Q|M|B|F|A|N|H|P)\d+\b"
    r"|\bC\d+[a-z]?\b"
    r"|\bG\d+(?:\.\d+)?\b"
)
# A block emitted by tools/render_claims.py or tools/comparison_snapshot.py.
GENERATED_REGION = re.compile(
    r"<!-- (claims|comparison):([\w-]+) -->.*?<!-- /\1:\2 -->", re.S)


#: One segment of a pointer: a quoted key - the way to address a key that itself contains a dot,
#: as a weight sweep's `"0.25"` does - a list index, or a bare key.
SEGMENT = re.compile(r'\["([^"]*)"\]|\[(\d+)\]|([^.\[\]]+)')


def resolve(data, pointer: str):
    """Walk a pointer: `a.b[2].c`, and `a["0.25"].c` for a key with a dot in it."""
    node = data
    for quoted, index, key in SEGMENT.findall(pointer):
        node = node[int(index)] if index else node[quoted or key]
    return node


def test_schema_is_complete() -> None:
    print("\n- manifest schema -")
    check("schema_version is present", MANIFEST.get("schema_version") == 1)
    claims = MANIFEST["claims"]
    check("the manifest carries claims", len(claims) > 50, str(len(claims)))

    missing = [c.get("id", "?") for c in claims
               if any(f not in c for f in REQUIRED)]
    check("every claim carries the required fields", not missing,
          ", ".join(missing[:5]))

    ids = [c["id"] for c in claims]
    check("claim ids are unique", len(ids) == len(set(ids)),
          ", ".join(sorted({i for i in ids if ids.count(i) > 1})))

    bad_printed = [c["id"] for c in claims
                   if not c["printed"] or not all(isinstance(p, str) and p.strip()
                                                  for p in c["printed"])]
    check("every claim declares how it is printed", not bad_printed,
          ", ".join(bad_printed[:5]))

    unknown_ds = sorted({c["dataset"] for c in claims
                         if c["dataset"] and c["dataset"] not in MANIFEST["datasets"]})
    check("every dataset reference resolves", not unknown_ds, ", ".join(unknown_ds))

    unknown_env = sorted({c["environment"] for c in claims
                          if c["environment"]
                          and c["environment"] not in MANIFEST["environments"]})
    check("every environment reference resolves", not unknown_env,
          ", ".join(unknown_env))

    unscoped = sorted({d for c in claims for d in c["cited_in"]
                       if d not in MANIFEST["scope"]["docs"]})
    check("claims are only cited in documents the manifest covers", not unscoped,
          ", ".join(unscoped))

    missing_produced_by = [c["id"] for c in claims
                           if not c.get("produced_by") and not c.get("declaration")]
    check("every claim names the source files that produced it", not missing_produced_by,
          ", ".join(missing_produced_by[:5]))
    #: The escape is a sentence, not a flag: a claim that opts out of the closure has to say
    #: where its value was decided, so the reader can go and check the decision.
    thin = [c["id"] for c in claims if c.get("declaration") and len(c["declaration"]) < 20]
    check("a declared value names where it was decided", not thin, ", ".join(thin))
    both = [c["id"] for c in claims if c.get("declaration") and c.get("produced_by")]
    check("a declared value carries no code closure to be invalidated by",
          not both, ", ".join(both))

    # `stale` is the only exemption from the freshness ratchet, so it is not free: a withdrawn
    # claim must say why and must not still be cited, and a claim with no recorded producing
    # commit must be withdrawn rather than published on an unknown engine.
    silent_stale = [c["id"] for c in claims
                    if "stale" in c and not (isinstance(c["stale"], str) and c["stale"].strip())]
    check("a withdrawn claim states its reason", not silent_stale,
          ", ".join(silent_stale[:5]))

    cited_while_stale = [c["id"] for c in claims if c.get("stale") and c["cited_in"]]
    check("a withdrawn claim is cited nowhere", not cited_while_stale,
          ", ".join(cited_while_stale[:5]))

    # `cited_in` was asserted and never verified, so the B8 README rewrite left five claims
    # pointing at a citation that no longer existed. The coverage check runs the other way -
    # every number in a document resolves to a claim - and cannot see a claim that thinks it
    # is printed somewhere it is not. Both directions or neither.
    absent = []
    for claim in claims:
        if claim.get("stale"):
            continue
        for doc in claim["cited_in"]:
            text = FENCE.sub("", (ROOT / doc).read_text(encoding="utf-8"))
            if not any(p in text for p in claim["printed"]):
                absent.append(f"{claim['id']} -> {doc}")
    check("every claimed citation is really there", not absent, "; ".join(absent[:5]))

    published_without_commit = [c["id"] for c in claims
                                if not c.get("stale") and not c["commit"]]
    check("a published claim names the commit that produced it",
          not published_without_commit, ", ".join(published_without_commit[:5]))

    print(f"       ({sum(1 for c in claims if c.get('stale'))} of {len(claims)} claims are "
          f"withdrawn; {sum(1 for c in claims if not c.get('stale'))} are published)")


