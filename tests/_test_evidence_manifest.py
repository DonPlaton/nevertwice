def _accounted_forms() -> tuple[set[str], list[tuple]]:
    forms: set[str] = set()
    # A withdrawn claim accounts for nothing. That is what makes withdrawal real rather than
    # declared: the moment a claim is marked `stale`, any document still printing its number
    # has an orphan, and this suite says so. Without it, task B8's 118 withdrawals would have
    # been a manifest edit that left every number sitting in the README.
    published = [c for c in MANIFEST["claims"] if not c.get("stale")]
    for entry in published + MANIFEST["external_citations"]:
        for p in entry["printed"]:
            p = p.strip()
            forms |= {p, p.lstrip("+−-"), p.replace(",", ""),
                      p.rstrip("%x×").rstrip(" ms").strip()}
        # A published claim's interval is part of the same measurement and resolves to the same
        # artifact, so a table may print `0.058 [0.029, 0.116]` without registering the bounds
        # as claims of their own. It is not a free pass: the bounds come from the claim's own
        # `ci`, so a document can only print the interval this run actually produced.
        ci = entry.get("ci")
        bounds = ((ci.get("low"), ci.get("high")) if isinstance(ci, dict)
                  else tuple(ci[:2]) if isinstance(ci, list) and len(ci) >= 2 else ())
        for b in bounds:
            if isinstance(b, (int, float)):
                forms |= {f"{b:.3f}", f"{b:.2f}", f"{b:g}"}
    for d in MANIFEST["drift"]:
        for p in d["printed"]:
            forms |= {p.strip(), p.replace(",", "")}
    # A non-metric may narrow itself to the lines it applies to. Ignoring that
    # `context` would let a broad pattern silently swallow real claims - which is
    # exactly what a mutation caught when this check first ran.
    rules = []
    for n in MANIFEST["non_metrics"]:
        match = ((lambda t, lit=n["literal"]: t == lit) if "literal" in n
                 else (lambda t, rx=re.compile(n["pattern"]): bool(rx.match(t))))
        ctx = re.compile(n["context"]) if n.get("context") else None
        rules.append((match, ctx))
    return forms, rules


def test_every_printed_number_is_accounted_for() -> None:
    print("\n- 100% of printed numbers resolve to evidence -")
    forms, rules = _accounted_forms()
    total = accounted = 0
    for doc in MANIFEST["scope"]["docs"]:
        text = FENCE.sub("", (ROOT / doc).read_text(encoding="utf-8"))
        lines = text.splitlines()
        orphans: dict[str, list[int]] = {}
        for m in NUMBER.finditer(text):
            token = m.group(0)
            total += 1
            lineno = text[:m.start()].count("\n") + 1
            line = lines[lineno - 1] if lineno <= len(lines) else ""
            if (token in forms or token.replace(",", "") in forms
                    or any(match(token) and (ctx is None or ctx.search(line))
                           for match, ctx in rules)):
                accounted += 1
                continue
            orphans.setdefault(token, []).append(lineno)
        detail = "; ".join(f"{t} (line {ls[0]})" for t, ls in
                           sorted(orphans.items())[:6])
        check(f"{doc}: every printed number is accounted for", not orphans, detail)
    check(f"overall coverage is 100% ({accounted}/{total})", accounted == total,
          f"{accounted}/{total}")


def _tracked_markdown() -> list[str] | None:
    """Every tracked .md, from git. None when git is unavailable.

    Globbing is not an option: research/embed_universal/data/ vendors thousands of
    third-party markdown files that git correctly ignores.
    """
    try:
        out = subprocess.run(["git", "ls-files", "*.md"], cwd=ROOT,
                             capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None
    return _docs_scope.documents(out.stdout.split()) if out.returncode == 0 else None


def _numeric_tokens(doc: str) -> int:
    """Evidence-bearing numeric tokens in a document.

    Tokens matched by a context-free non-metric rule - a year, a month, a Python
    version, a bare single digit - are excluded. Otherwise dating a comparative claim
    ("measured 2026-07-05") would count as *adding* unevidenced numbers and trip the
    ratchet, punishing exactly the change task B3 asks for.

    Register-ID-shaped tokens (`ID_TOKEN` above - W17, R12, G5.1...) are stripped WHOLE
    before the plain number scan runs, not filtered by value afterward - a real
    measurement that happens to share the same digits elsewhere on the page (a "17%"
    with no letter prefix) is untouched, only the ID's own span is removed.
    """
    text = (ROOT / doc).read_text(encoding="utf-8", errors="replace")
    # Numbers inside a generated region are produced from committed data by a tool
    # whose own check runs in CI. They are the opposite of unregistered, so counting
    # them would make generating a table look like adding unevidenced claims.
    text = GENERATED_REGION.sub("", text)
    text = FENCE.sub("", text)
    text = ID_TOKEN.sub("", text)
    ignore = [re.compile(n["pattern"]) for n in MANIFEST["non_metrics"]
              if "pattern" in n and not n.get("context")]
    literals = {n["literal"] for n in MANIFEST["non_metrics"]
                if "literal" in n and not n.get("context")}
    return sum(1 for t in NUMBER.findall(text)
               if t not in literals and not any(rx.match(t) for rx in ignore))


