def model(name: str, digest: str, modified: str = "2026-09-01T00:00:00Z") -> dict:
    return {"name": name, "model": name, "digest": digest, "size": 1, "modified_at": modified}


class Fake:
    """A stateful fake Ollama. ``mode`` bends one behaviour per test."""

    def __init__(self, mode: str = "ok", version: str = "0.12.3") -> None:
        self.mode, self.version, self.seen, self.bodies, self.shows = mode, version, [], [], []
        self.models = [model("bge-m3:latest", BASE_DIGEST), model("qwen3.6:27b", "a50eda8ed977" + "0" * 52),
                       model("owner-private:7b", "4" * 64)]
        self.loaded = [{"name": "qwen3.6:27b"}]
        self.tags_reads = 0
        if mode == "tag_present":
            self.models.append(model(D.TAG + ":latest", "5" * 64))
        if mode == "base_absent":
            self.models = [m for m in self.models if not m["name"].startswith("bge-m3")]

    def tags(self) -> dict:
        self.tags_reads += 1
        if self.mode == "base_moves" and self.tags_reads >= 2:      # after the inventory run, before the create
            for m in self.models:
                if m["name"] == "bge-m3:latest":
                    m["digest"] = "9" * 64
        return {"models": [dict(m) for m in self.models]}

    def create(self, body: dict) -> dict:
        self.bodies.append(body)
        self.models.append(model(D.TAG + ":latest", "6" * 64, "2026-09-26T23:59:00Z"))
        if self.mode == "create_touches_other":
            self.models[1]["modified_at"] = "2026-09-26T23:59:00Z"
        if self.mode == "create_removes_other":
            self.models = [m for m in self.models if m["name"] != "owner-private:7b"]
        if self.mode == "create_adds_extra":
            self.models.append(model("stray:1b", "c" * 64))
        if self.mode == "create_loads":
            self.loaded.append({"name": "bge-m3:latest"})
        return {"status": "success"}

    def show(self, body: dict) -> dict:
        name = body.get("model") or body.get("name")
        tag = name.startswith(D.TAG)
        self.shows.append((name, bool(self.bodies)))
        if self.mode == "base_no_from" and not tag:
            return {"modelfile": "# Modelfile\n# no FROM line\n", "parameters": ""}
        if self.mode == "base_bad_params" and not tag:
            return {**REAL_BASE_SHOW, "parameters": "a line that is not name-value\nnum_batch"}
        if self.mode == "no_from_after" and self.bodies:
            return {"modelfile": "# Modelfile\n", "parameters": "num_batch 2048"} if tag else {"modelfile": "# Modelfile\n"}
        if not tag:
            return dict(REAL_BASE_SHOW)                    # the real bge-m3 on 0.34.4: no "parameters" key at all
        blob = BLOB if self.mode != "other_blob" else "sha256-" + "b" * 64
        out = {"modelfile": f"# Modelfile generated\nFROM C:\\Users\\x\\.ollama\\models\\blobs\\{blob}\n",
               "parameters": "num_batch                      2048" if self.mode != "no_param" else ""}
        if self.mode == "tag_no_params":
            del out["parameters"]
        return out


def serve(fake: Fake):
    class H(BaseHTTPRequestHandler):
        def log_message(self, *a):
            pass

        def _send(self, obj):
            data = json.dumps(obj).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self):
            fake.seen.append(("GET", self.path))
            if self.path == "/api/version":
                self._send({"version": fake.version})
            elif self.path == "/api/tags":
                self._send(fake.tags())
            elif self.path == "/api/ps":
                self._send({"models": list(fake.loaded)})
            else:
                self._send({})

        def do_POST(self):
            fake.seen.append(("POST", self.path))
            body = json.loads(self.rfile.read(int(self.headers.get("Content-Length") or 0)) or b"{}")
            self._send(fake.create(body) if self.path == "/api/create" else fake.show(body) if self.path == "/api/show" else {})

    srv = ThreadingHTTPServer(("127.0.0.1", 0), H)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


TMP = Path(tempfile.mkdtemp(prefix="nvt3_d1tag_"))


def inventory(tag: str, *, digest: str = BASE_DIGEST, version: str = "0.12.3", problems: list | None = None) -> Path:
    """An A3.h inventory record as ollama_inventory writes it (only the fields d1_tag reads)."""
    d = TMP / tag / "_inventory" / "ollama" / "o1"
    d.mkdir(parents=True)
    rec = {"run": "o1", "version": version, "problems": problems or [],
           "pins": {"bge-m3": {"present": True, "found": "bge-m3:latest", "digest": digest, "digest12": digest[:12]}}}
    (d / "record.json").write_bytes(json.dumps(rec).encode())
    return d / "record.json"


def run(tag: str, mode: str = "ok", **inv) -> tuple[dict, Fake]:
    fake = Fake(mode)
    srv = serve(fake)
    try:
        rec = D.run_create(TMP / tag / "runs", run="d1", inventory=inventory(tag, **inv), port=srv.server_address[1])
    finally:
        srv.shutdown()
    return rec, fake


