def check(name: str, cond: bool, detail: str = "") -> None:
    global PASSED, FAILED
    if cond:
        PASSED += 1
        print(f"  ok   {name}")
    else:
        FAILED += 1
        print(f"  FAIL {name}" + (f" - {detail}" if detail else ""))


def refused(fn, words: str = "") -> bool:
    try:
        fn()
    except D.TagRefused as e:
        return words in str(e)
    except Exception:  # noqa: BLE001
        return False
    return False


BASE_DIGEST = "3" * 64
BLOB = "sha256-" + "a" * 64


#: The real /api/show key set of bge-m3:latest on Ollama 0.34.4 (the auditor's read-only measurement, 2026-09-27):
#: capabilities, details, license, model_info, modelfile, modified_at, template - and NO "parameters".
